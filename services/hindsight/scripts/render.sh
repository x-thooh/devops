#!/usr/bin/env bash
# hindsight 存储后端 = 复用 pg 栈（DEC-55）。render 按 MODE 选目标：
#   solo → patroni-1:5432；ha → pg-haproxy-1:5000（主写，非 leader 由 haproxy 分发）
# 密码走 env/.env（HINDSIGHT_DB_PASSWORD / PG_SUPERUSER_PASSWORD），渲染物含 IP → 落 .data/active/。
# 无配置文件模板可渲染：DATABASE_URL 是本栈唯一的渲染产物；role/db/extension 由 pre.sh 建。
set -euo pipefail

STACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "${STACK_DIR}/../../scripts/lib.sh"

MODE="${1:-solo}"
ACTIVE="${STACK_DIR}/.data/active"
ensure_dir "${ACTIVE}"

# shellcheck disable=SC1091
set -a; source "${DEVOPS_ROOT}/env/.env"; set +a
DB_PASS="${HINDSIGHT_DB_PASSWORD:?HINDSIGHT_DB_PASSWORD missing in env/.env}"

if [[ "${MODE}" == "solo" ]]; then
    db_host="$(ip_of patroni-1)"
    db_port=5432
else
    db_host="$(ip_of pg-haproxy-1)"
    db_port=5000
fi

cat >"${ACTIVE}/hindsight.env" <<EOF
# generated by scripts/render.sh (mode=${MODE}); do not edit
HINDSIGHT_API_DATABASE_URL=postgresql://hindsight:${DB_PASS}@${db_host}:${db_port}/hindsight
EOF
chmod 600 "${ACTIVE}/hindsight.env"

echo "rendered hindsight (mode=${MODE}, db=${db_host}:${db_port})"
